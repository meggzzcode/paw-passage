// More themes, so each kind of adventure gets its own look inside a family: its own palette, motif pair,
// frame, backdrop and printed wording. Names and wording here are generic design names, not adventure titles.
import type { FontKey, KeepsakeFamily, MotifId, Palette, ThemeConfig } from "./themes";

type Frame = ThemeConfig["frame"];

function pal(s: string): Palette {
  const [bg, bg2, ink, accent, accent2, muted, card] = s.split(",").map((x) => x.trim()) as [
    string,
    string,
    string,
    string,
    string,
    string,
    string,
  ];
  return { bg, bg2, ink, accent, accent2, muted, onAccent: "#ffffff", card };
}

export function x(
  id: string,
  family: KeepsakeFamily,
  label: string,
  palette: string,
  display: FontKey,
  body: FontKey,
  upper: boolean,
  motif: MotifId,
  motif2: MotifId,
  frame: Frame,
  words: Record<string, string>,
  extra: { variant?: string; pattern?: ThemeConfig["pattern"] } = {},
): ThemeConfig {
  return {
    id,
    family,
    label,
    palette: pal(palette),
    display,
    body,
    upper,
    motif,
    motif2,
    frame,
    words,
    ...extra,
  };
}

