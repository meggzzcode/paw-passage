#!/usr/bin/env node
// Rebuilds the whole owner marketing package from the repo. Outside the repo only; nothing generated is committed.
// Usage: node marketing/build-owner-package.mjs [--out DIR] [--skip-render] [--drive-id ID] [--site ORIGIN] [--no-zip]
// Steps: render both pin sets, write PINS.csv, copy site assets and docs, write READMEs, zip.
// Re-run after docs/IMAGE-CREDITS.md appears so the pending photo examples flip to FINAL in site-assets/README.md.
import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  copyFileSync,
  existsSync,
  readdirSync,
  statSync,
  rmSync,
} from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const args = process.argv.slice(2);
const arg = (n, d) => (args.includes(n) ? args[args.indexOf(n) + 1] : d);
const out = resolve(arg("--out", join(root, "..", "paws-passage-export", "owner-package")));
if (out.startsWith(root + "/")) {
  console.error("Refusing to build the package inside the repository.");
  process.exit(1);
}
const date = new Date().toISOString().slice(0, 10);
// The live origin is not set in src/config/site.ts yet. Pass --site https://your-domain (or set it once known).
const SITE = arg("--site", "https://YOUR-SITE-DOMAIN").replace(/\/$/, "");
const credits = existsSync(join(root, "docs/IMAGE-CREDITS.md"));

// Keep a Drive id recorded earlier unless a new one is passed.
let driveId = arg("--drive-id", null);
const readmePath = join(out, "OWNER-README.md");
if (!driveId && existsSync(readmePath)) {
  driveId = readFileSync(readmePath, "utf8").match(/^Drive backup file id: (\S+)/m)?.[1] ?? null;
}

mkdirSync(out, { recursive: true });
const ls = (d) => (existsSync(d) ? readdirSync(d) : []);

// 1. Render pins.
if (!args.includes("--skip-render")) {
  const gen = join(here, "pins/generate.mjs");
  execFileSync("node", [gen, "--out", join(out, "pins/general")], { stdio: "inherit" });
  execFileSync("node", [gen, "--set", "article", "--out", join(out, "pins/article")], {
    stdio: "inherit",
  });
}

// 2. PINS.csv
const csvCell = (s) => `"${String(s ?? "").replace(/"/g, '""')}"`;
const rows = [
  ["file", "pin_title", "description", "destination_url_with_utm", "source", "status", "alt_text"],
];
let completed = 0;
let concept = 0;
for (const [source, json, dir] of [
  ["general", "pins.json", "pins/general"],
  ["article", "article-pins.json", "pins/article"],
]) {
  const { pins } = JSON.parse(readFileSync(join(here, "pins", json), "utf8"));
  for (const p of pins) {
    const rel = `${dir}/${p.id}.png`;
    const ok = existsSync(join(out, rel)) && statSync(join(out, rel)).size > 10000;
    ok ? completed++ : concept++;
    const alt = `Pinterest pin: ${p.kicker}. ${p.headline}. ${p.sub}`.replace(/\s+/g, " ");
    rows.push([
      rel,
      p.title,
      p.description,
      `${SITE}${p.destination}`,
      source,
      ok ? "COMPLETED graphic" : "CONCEPT only",
      alt,
    ]);
  }
}
writeFileSync(join(out, "PINS.csv"), rows.map((r) => r.map(csvCell).join(",")).join("\n") + "\n");

// 3. Site assets
const SA = join(out, "site-assets");
rmSync(SA, { recursive: true, force: true });
const lines = [];
for (const dir of ["examples", "demo", "journal"]) {
  mkdirSync(join(SA, dir), { recursive: true });
  for (const f of ls(join(root, "public", dir))) {
    copyFileSync(join(root, "public", dir, f), join(SA, dir, f));
    let status;
    if (dir === "examples" && f.endsWith("-photo.webp"))
      status = credits
        ? "FINAL (docs/IMAGE-CREDITS.md exists; confirm this file is listed there)"
        : "PENDING until docs/IMAGE-CREDITS.md exists (real-dog-photo keepsake example, being produced; treat the current file as a placeholder)";
    else if (dir === "journal")
      status = credits
        ? "FINAL (provenance per docs/IMAGE-CREDITS.md)"
        : "IN USE on the site; provenance record pending (docs/IMAGE-CREDITS.md does not exist yet)";
    else
      status =
        "FINAL (illustrative keepsake art generated by the project; not a real customer photo)";
    lines.push(`| ${dir}/${f} | ${status} |`);
  }
}
writeFileSync(
  join(SA, "README.md"),
  `# Site assets (copied from public/examples, public/demo, public/journal)

Built ${date}. docs/IMAGE-CREDITS.md exists: **${credits ? "yes" : "no"}**.

- Examples and demo images are keepsake and product demonstrations, not customer photos.
- Files marked PENDING are not final: the real-dog-photo keepsake examples are still being produced. Do not present them as finished or as customer work.
- To refresh after the photo examples and docs/IMAGE-CREDITS.md land: from the repo root run \`node marketing/build-owner-package.mjs --skip-render\` (add \`--drive-id <id>\` if you want to keep a record), then re-zip and re-upload.

| File | Status |
| ---- | ------ |
${lines.join("\n")}
`,
);

// 4. Docs
const D = join(out, "docs");
mkdirSync(D, { recursive: true });
const docCopies = [
  ["docs/MARKETING.md", "MARKETING.md"],
  ["docs/EMAIL-NUDGES.md", "EMAIL-NUDGES.md"],
  ["marketing/README.md", "PIN-GENERATOR-README.md"],
  ["docs/IMAGE-CREDITS.md", "IMAGE-CREDITS.md"],
  ["public/fonts/OFL-DM-Sans.txt", "licenses/OFL-DM-Sans.txt"],
  ["public/fonts/OFL-Fraunces.txt", "licenses/OFL-Fraunces.txt"],
];
for (const [src, dst] of docCopies) {
  if (!existsSync(join(root, src))) continue;
  mkdirSync(dirname(join(D, dst)), { recursive: true });
  copyFileSync(join(root, src), join(D, dst));
}
writeFileSync(
  join(D, "LICENSING.md"),
  `# Image, art and font licensing (summary, ${date})

- **Pin art (all 60 pins): original.** Layouts are HTML and CSS in marketing/pins/templates; the dog head and scene motifs are original SVG drawn for this project (templates/motifs). No stock photos, no third-party artwork, no AI image generation, no network access during rendering.
- **Fonts: Fraunces and DM Sans**, self-hosted, SIL Open Font License 1.1 (license texts in docs/licenses/).
- **Keepsake demonstration art** (site-assets/examples, demo): generated by project code. Real-dog-photo examples are pending; see site-assets/README.md.
- **Journal pictures** (site-assets/journal): in use on the site. Per docs/JOURNAL.md every picture must be original or properly licensed and recorded in docs/IMAGE-CREDITS.md. ${credits ? "That record is included as docs/IMAGE-CREDITS.md." : "That record does not exist yet, so provenance is UNVERIFIED in this package. Do not assume the pictures are owned outright."}
- Guide photos on the site (if any) are licensed from Unsplash under the Unsplash License: a license to use, not ownership (docs/OWNERSHIP-TRANSFER.md).
- Not legal advice.
`,
);
writeFileSync(
  join(D, "CAMPAIGN-TRACKING.md"),
  `# Campaign tracking guide

## UTM convention
Every pin link is the site address plus the destination in PINS.csv, copied exactly: \`utm_source=pinterest&utm_medium=social&utm_campaign=<name>&utm_content=<pin id>\`.
- Journal pins: \`utm_campaign=<article-slug>-<1|2|3>\` (one value per pin).
- General pins: \`utm_campaign\` keeps the earlier theme name (ending \`-legacy\`) and \`utm_content\` is the pin id, so single pins can be told apart.
- Never add personal data to a link. Keep names lowercase with hyphens.

## What is measurable
- In Pinterest analytics: impressions, saves, outbound clicks per pin (free business account).
- On the site: visits and pageviews by utm_campaign and utm_content in the site's aggregate analytics, and the aggregate site events (for example purchase_cta_clicked, checkout_started).

## Limits (state these plainly)
- Campaign data is **not connected to confirmed Gumroad purchases yet**. A pin can be linked to visits and checkout clicks, not to a sale.
- Sales cannot be credited to one pin. Judge pins by outbound clicks and visits over several weeks.
- Some browsers strip or block tracking parameters; counts are a lower bound.
- Nothing is verified live until the owner runs the UTM check in the COWORK TASKS list of the hand-off.

## Weekly routine (about 20 to 30 minutes, no paid scheduler)
1. Monday: choose 3 to 5 pins (see PINS.csv), mixing sources, favoring the season.
2. Upload each PNG, paste pin_title and description, set the link exactly as in destination_url_with_utm, pick the board.
3. Optional: Pinterest's own free scheduling for business accounts to spread posts across the week.
4. Friday: note outbound clicks per pin and the best and weakest utm_campaign. Keep a private note of what was posted.
5. Monthly: retire the weakest pins, edit a headline in marketing/pins/*.json, re-render with this script.

## Email nudges
Proposal only, not built: docs/EMAIL-NUDGES.md (buyers only, through Gumroad).
`,
);

// 5. Concepts (not graphics)
writeFileSync(
  join(out, "PROPOSED-CONCEPTS.md"),
  `# PROPOSED concepts (no finished graphics exist for these)

Nothing on this page is ready to publish. Each item is an idea or draft text only.

- Seasonal pin calendar and new pin themes: docs/MARKETING.md section 4 (description only; render by adding entries to marketing/pins/pins.json).
- Gift marketing: docs/MARKETING.md section 6 (evaluation only; the gifting flag is OFF until verified on Gumroad).
- Weekly email nudges to buyers: docs/EMAIL-NUDGES.md (proposal for owner approval, nothing built).
- Real-dog-photo keepsake examples: in production by another worker; see site-assets/README.md.
- Commercial test plan: docs/MARKETING.md section 7.

COMPLETED graphics are only the ${completed} pins in pins/ (listed in PINS.csv with status COMPLETED graphic).
`,
);

// 6. Owner README
writeFileSync(
  readmePath,
  `# Paws & Passage owner marketing package

Built ${date} by marketing/build-owner-package.mjs. ${completed} pin graphics COMPLETED, ${concept} concept-only.
Drive backup file id: ${driveId ?? "(not yet uploaded)"}

## Layout
| Path | What it is |
| ---- | ---------- |
| pins/general/ | 30 general Pinterest pins, 1000x1500 PNG. COMPLETED graphics. |
| pins/article/ | 30 Journal pins (3 per article), 1000x1500 PNG. COMPLETED graphics. |
| PINS.csv | One row per pin: file, title, description, link with UTM, source, status, alt text. Open in any spreadsheet. |
| site-assets/ | Copies of the site's example, demo and journal images with a README of what is final or pending. |
| docs/ | Marketing plan, tracking guide, licensing summary, email nudge proposal, generator README, font licenses (and IMAGE-CREDITS.md once it exists). |
| PROPOSED-CONCEPTS.md | Ideas and drafts that are NOT finished graphics. |

## Using it
1. Open PINS.csv. For each pin you post, upload the PNG, paste pin_title and description, use the alt text, set the link to destination_url_with_utm exactly. The live domain is not configured yet, so links start with https://YOUR-SITE-DOMAIN: rebuild with \`--site https://your-real-domain\` once it is set, before posting.
2. Use docs/CAMPAIGN-TRACKING.md for the weekly routine and the attribution limits (campaign data is not yet tied to confirmed Gumroad purchases).
3. Pins say nothing about paid adventure content, carry no hashtags, no discounts and no deadlines. Keep it that way.
4. Pin destinations are the Journal articles, the things-to-do hub and /discover. The old landing pages are redirects and are not used.

## A future buyer
The package is self-contained: the pins, links and records can be reused as is. The generator and templates live in the repo (marketing/), so the buyer can edit marketing/pins/*.json and re-render with \`node marketing/build-owner-package.mjs\`. Replace the Pinterest account, boards and site domain with their own; the Pinterest account itself is not transferable by this package. Check licensing in docs/LICENSING.md before reuse.

## Refresh
From the repo root: \`node marketing/build-owner-package.mjs\` (add \`--skip-render\` to reuse the existing PNGs). Then zip the folder and re-upload.
`,
);

// 7. Zip
if (!args.includes("--no-zip")) {
  const zip = join(dirname(out), `owner-package-${date}.zip`);
  rmSync(zip, { force: true });
  execFileSync("zip", ["-rq", zip, "."], { cwd: out });
  console.log(`Zip: ${zip} (${(statSync(zip).size / 1048576).toFixed(1)} MB)`);
}
console.log(`Package: ${out}; ${completed} completed, ${concept} concept-only.`);
