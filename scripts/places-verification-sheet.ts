// Prints the list of dog-rules places that still need checking against their official page, for the
// verification prompt in docs/COWORK-VERIFY-PLACES.md. Reads content/places/*.yml, so it is always current.
//   bun scripts/places-verification-sheet.ts           print the list
//   bun scripts/places-verification-sheet.ts --write   also refresh the list inside docs/COWORK-VERIFY-PLACES.md
// Places already verified (with source, quote and date) are skipped.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";

const root = join(import.meta.dir, "..");
const dir = join(root, "content", "places");
const START = "<!-- PLACES:START (generated by scripts/places-verification-sheet.ts) -->";
const END = "<!-- PLACES:END -->";

type Row = { area: string; rule: string; note?: string };
const ruleText: Record<string, string> = { yes: "dogs allowed", leash: "allowed on a leash", no: "NOT allowed", some: "allowed in some places" };

export function buildSheet(): string {
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => /\.ya?ml$/.test(f)).sort() : [];
  const items: string[] = [];
  for (const f of files) {
    const y = (parse(readFileSync(join(dir, f), "utf8")) ?? {}) as Record<string, unknown>;
    if (y["status"] === "verified" && y["sourceUrl"] && y["sourceQuote"] && y["lastChecked"]) continue;
    const slug = f.replace(/\.ya?ml$/, "");
    const rows = ((y["dogsAllowed"] as Row[] | undefined) ?? []).map((r) => `${r.area}: ${ruleText[r.rule] ?? r.rule}${r.note ? ` (${r.note})` : ""}`);
    const excl = (y["exclusions"] as string[] | undefined) ?? [];
    const lines = [
      `${items.length + 1}. **${y["name"]}** (slug: \`${slug}\`)`,
      `   - File: \`content/places/${f}\``,
      `   - Managed by: ${y["managedBy"]}`,
      `   - Official page we cited: ${y["sourceUrl"] ?? "(none recorded)"}`,
      `   - Our current claim (from the article \`${y["claimFrom"] ?? "unknown"}\`):`,
      ...rows.map((r) => `     - ${r}`),
      ...(y["leash"] ? [`     - Leash: ${y["leash"]}`] : []),
      ...(y["fees"] ? [`     - Fees: ${y["fees"]}`] : []),
      ...(excl.length ? [`     - Not allowed: ${excl.join("; ")}`] : []),
      ...(y["seasonal"] ? [`     - Seasonal: ${y["seasonal"]}`] : []),
      ...(y["conflictNote"] ? [`     - Known conflict we noted: ${y["conflictNote"]}`] : []),
    ];
    items.push(lines.join("\n"));
  }
  return items.length ? items.join("\n\n") : "(No places need checking: every place is already verified.)";
}

const sheet = buildSheet();
console.log(sheet);

if (process.argv.includes("--write")) {
  const doc = join(root, "docs", "COWORK-VERIFY-PLACES.md");
  const text = readFileSync(doc, "utf8");
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < 0) throw new Error(`${doc} has no ${START} ... ${END} markers`);
  writeFileSync(doc, `${text.slice(0, a + START.length)}\n\n${sheet}\n\n${text.slice(b)}`);
  console.error(`Updated ${doc}`);
}
