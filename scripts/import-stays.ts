// Converts data/stays.csv (same columns as data/stays-template.csv) into src/content/stays/verified.ts.
// Usage: bun scripts/import-stays.ts data/stays.csv
// Blank cells = "not confirmed" (null). Lists use "|" separators. Only rows with status "verified" go live.
import { readFileSync, writeFileSync } from "node:fs";

function parseCsv(text: string): string[][] {
  const rows: string[][] = []; let row: string[] = []; let cell = ""; let q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (c === '"') q = false; else cell += c; }
    else if (c === '"') q = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n" || c === "\r") { if (c === "\r" && text[i + 1] === "\n") i++; row.push(cell); rows.push(row); row = []; cell = ""; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows.filter((r) => r.some((x) => x.trim()));
}

const file = process.argv[2] ?? "data/stays.csv";
const [header, ...rows] = parseCsv(readFileSync(file, "utf8"));
if (!header) throw new Error("CSV is empty");
const bool = (v: string) => (v === "" ? null : v.toLowerCase() === "true");
const num = (v: string) => (v === "" ? null : Number(v));
const list = (v: string) => (v ? v.split("|").map((s) => s.trim()) : []);
const errors: string[] = [];
const stays = rows.map((r, i) => {
  const o = Object.fromEntries(header.map((h, j) => [h.trim(), (r[j] ?? "").trim()]));
  for (const k of ["slug", "name", "status", "type", "state", "town", "image"]) if (!o[k]) errors.push(`Row ${i + 2}: missing ${k}`);
  if (o.status === "verified" && !o.lastVerified) errors.push(`Row ${i + 2}: verified stays need lastVerified`);
  return {
    slug: o.slug, name: o.name, status: o.status, type: o.type, state: o.state, town: o.town,
    summary: o.summary, description: o.description, sleeps: num(o.sleeps), bedrooms: num(o.bedrooms),
    maxDogs: num(o.maxDogs), largeDogsOk: bool(o.largeDogsOk), weightLimitLbs: num(o.weightLimitLbs),
    fencedYard: o.fencedYard || null, ...(o.fenceNotes ? { fenceNotes: o.fenceNotes } : {}),
    privateOutdoor: bool(o.privateOutdoor),
    petFee: o.petFeeAmount === "" ? null : { amount: Number(o.petFeeAmount), basis: o.petFeeBasis || "stay" },
    breedRestrictions: bool(o.breedRestrictions), beach: o.beach === "true", mountain: o.mountain === "true", hotTub: bool(o.hotTub),
    nearby: list(o.nearby), houseRules: list(o.houseRules), image: o.image, sourceUrl: o.sourceUrl,
    lastVerified: o.lastVerified || null, photoPermission: o.photoPermission === "true",
    ...(o.affiliateId ? { affiliateId: o.affiliateId } : {}),
  };
});
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
writeFileSync("src/content/stays/verified.ts", `import type { Stay } from "./types";\n\n// Generated by scripts/import-stays.ts from ${file}. Edit the CSV and re-run, or edit here directly.\nexport const verifiedStays: Stay[] = ${JSON.stringify(stays, null, 2)} as Stay[];\n`);
console.log(`Wrote ${stays.length} stays (${stays.filter((s) => s.status === "verified").length} verified).`);
